/**
 * 業種ごとの、はじめの設定（カウンセリング）の出し分け。
 *
 * ★2026-09-04 三上様指摘：
 *   質問の候補チップも例文も治療院（整体・整骨院）前提で書かれていたため、
 *   カフェや教室、士業のお客様が「骨盤矯正」「痛い施術ですか？」といった
 *   自分と関係のない候補を見せられて、答えづらくなっていた。
 *
 *   最初の質問（業種）で答えていただいた内容から業種のグループを判定し、
 *   そのあとの質問の候補・例文・言い回しをその業種のものに差し替える。
 *
 * 判定できないときは、どの業種でも読める中立の内容にする。
 * （治療院向けの内容を「全員の既定」にはしない。それが今回の原因だった）
 *
 * 保存先（CounselingAnswers のキー）は業種によらず共通。
 * 生成側は今までどおり同じフィールドを読むだけでよい。
 */

import type { CounselingQuestion } from './counseling';

/** 質問文・ヘルプの中の言い回しを、業種に合わせて置き換えるための語。 */
export interface IndustryWords {
  /** 提供しているものの呼び方。既定文の「施術」を置き換える */
  service: string;
  /** お客さんの呼び方。既定文の「患者さん」を置き換える */
  customer: string;
  /** 自分のお店の呼び方。既定文の「自院」を置き換える */
  shop: string;
  /** 来てもらうことの呼び方。既定文の「来店」を置き換える */
  visit: string;
}

/** 質問IDごとの候補チップ・例文の差し替え */
export type QuestionOverrides = Record<string, {
  suggestions?: string[];
  examples?: string[];
  /** 質問文そのものを差し替えたいとき（「施術のあと」が業種に合わない場合など） */
  prompt?: string;
  helper?: string;
}>;

/**
 * 業種の「大きなくくり」。言い回し（施術／レッスン等）と、
 * その くくり 全体で通用する候補・例文を持つ。
 */
export interface IndustryProfile {
  key: string;
  label: string;
  /** 業種の回答にこの語が含まれていればこのグループと判定する */
  match: string[];
  words: IndustryWords;
  q: QuestionOverrides;
}

/**
 * 細かい業種。★2026-09-04 三上様指示で追加。
 *
 * 「美容」ひとくくりだと、美容室の方にエステの候補が出てしまう。
 * ここでは くくり からの**差分だけ**を持ち、書いていない質問は
 * くくり の内容をそのまま使う（同じ内容を何度も書かないため）。
 */
export interface IndustrySubtype {
  key: string;
  label: string;
  /** どの くくり に属するか（言い回しと既定の候補を受け継ぐ） */
  group: string;
  /** 業種の回答にこの語が含まれていれば採用（上から順に先勝ち） */
  match: string[];
  /** くくり の内容を上書きする質問だけ書く */
  q?: QuestionOverrides;
  /** 言い回しだけ変えたいとき（例：動物病院の「飼い主さん」） */
  words?: Partial<IndustryWords>;
}

