/**
 * 業種が「商圏型」かどうかの判定。
 *
 * 商圏型＝お客様が実際にその場所へ足を運ぶ業種（整体院・美容室・飲食店・ジム等）。
 * この場合、「◯◯駅から徒歩◯分」と狭く言い切るほど新規の反応が上がる
 * （2026-08-20 実測：県名より駅＋徒歩分数のほうが明確に強い）。
 *
 * 一方、Web制作・広告運用・オンラインサービスのように来店を伴わない業種では、
 * 駅からの距離を書いても読み手の自分事化につながらない。むしろ
 * 「岡山県内の店舗オーナー」のような“対象の絞り込み”のほうが効く。
 *
 * 判定方針：
 *  - このアプリの利用者は実店舗がほとんどなので **既定は商圏型（true）**。
 *  - 「来店を伴わないことがはっきり分かる語」が業種に含まれるときだけ false にする。
 *  - 迷う場合は true 側に倒す（商圏を書いても害は小さく、書かない損失のほうが大きい）。
 */

/** 来店を伴わない（＝商圏を書いても意味が薄い）業種を示す語 */
const NON_LOCAL_KEYWORDS = [
  // Web・IT・制作
  'web集客', 'web制作', 'ウェブ制作', 'ホームページ制作', 'lp制作', 'サイト制作',
  'システム開発', 'アプリ開発', 'it', 'saas', 'ソフトウェア',
  // 広告・マーケティング・コンサル・代行
  '広告運用', '広告代理', 'マーケティング支援', 'コンサル', '運用代行', '集客支援',
  // オンライン・通販
  'オンライン', 'onlineのみ', 'ec', '通販', 'ネットショップ',
];

/** 逆に、上の語を含んでいても「実店舗」だと分かる語（誤判定の救済） */
const LOCAL_OVERRIDE_KEYWORDS = [
  '整体', '整骨', '接骨', '鍼灸', 'はり', 'きゅう', 'カイロ', 'マッサージ',
  '美容室', 'ヘアサロン', '理容', 'ネイル', 'まつげ', 'エステ', 'サロン',
  'ピラティス', 'ヨガ', 'ジム', 'パーソナルトレーニング', 'スタジオ',
  '飲食', 'カフェ', 'レストラン', '居酒屋', 'ラーメン', '美容外科', 'クリニック',
  '歯科', '医院', '薬局', '教室', 'スクール', '幼稚園', '保育',
];

function normalize(s: string): string {
  return (s || '')
    .toLowerCase()
    .replace(/[Ａ-Ｚａ-ｚ０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
    .replace(/\s+/g, '');
}

/**
 * 商圏型の業種か。
 * @param businessType プロジェクトの業種テキスト（自由入力）
 */
export function isLocalCatchmentBusiness(businessType: string | null | undefined): boolean {
  const b = normalize(businessType ?? '');
  if (!b) return true; // 未入力なら既定どおり商圏型として扱う

  // 実店舗を示す語があれば、それを優先して商圏型と判定する
  if (LOCAL_OVERRIDE_KEYWORDS.some((k) => b.includes(normalize(k)))) return true;

  // 来店を伴わない語が含まれていれば非商圏型
  if (NON_LOCAL_KEYWORDS.some((k) => b.includes(normalize(k)))) return false;

  return true;
}
