import { PLANS, type PlanConfig } from './plans';

/** 案内に使う通常プラン（キャンペーン価格・代理店クライアント枠は除く） */
const PUBLIC_PLAN_IDS = ['free', 'light', 'pro', 'business', 'agency'] as const;

const limitText = (n: number | undefined, unit: string) =>
  n === undefined ? '—' : n < 0 ? '無制限' : `${n}${unit}`;

function planLine(p: PlanConfig): string {
  const f = p.features;
  const price = p.priceMonthly === 0 ? '無料' : `月額 ${p.priceMonthly.toLocaleString()}円（税込）`;
  const auto = (f.maxAutoPostsPerDay ?? 0) <= 0
    ? '自動投稿なし（手動での作成をお試しいただけます）'
    : `1日 ${f.maxAutoPostsPerDay} 回まで自動投稿`;
  return [
    `- ${p.name}：${price}`,
    `  ・Threadsアカウント連携：${limitText(f.maxThreadsAccounts, '件')}`,
    `  ・${auto}`,
    `  ・AI生成：${(f.maxAiGenerations ?? 0) < 0 ? '無制限' : `月${f.maxAiGenerations}回`}`,
    `  ・LINEで操作できる人数：${limitText(f.maxLineLinks, '人')}`,
  ].join('\n');
}

/** プラン表（自動応答のプロンプトにそのまま差し込む） */
export function plansKnowledge(): string {
  return PUBLIC_PLAN_IDS
    .map((id) => PLANS[id])
    .filter(Boolean)
    .map((p) => planLine(p as PlanConfig))
    .join('\n');
}

