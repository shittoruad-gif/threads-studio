/**
 * LINEに届いた文章が「ご質問」なのか「ご依頼・投稿の材料」なのかの仕分け。
 *
 * ここで「ご依頼」と分かったものは、担当者への自動通知の対象から外す
 * （お客様が投稿文や実績を送ってこられただけで運営に通知が飛ぶと、
 *  本当に困っている方のご連絡が埋もれるため）。
 *
 * 判定を変えるときは server/requestKind.test.ts の実例も合わせて直すこと。
 */

/**
 * 投稿用の文章をそのまま貼られたか。
 * ★長文・改行あり・疑問符なし（＋絵文字やハッシュタグが混じる）は、ご質問ではなく
 *   「投稿文の貼り付け」であることがほとんど。ご質問扱いにすると自動応答が的外れな
 *   返事をし、担当者にも「質問」として上がってくる（2026-09-03 に2件発生）。
 */
/**
 * 困りごと・操作のお尋ねに出てくる言葉。
 * これが入っていれば、長くて飾りがあっても「ご質問」として扱う（投稿文とみなさない）。
 */
const SUPPORT_QUESTION_RE =
  /(できません|できない|エラー|不具合|届かない|届きません|入れません|ログイン|連携|解約|請求|お支払|支払い|料金|プラン|やり方|どうすれば|どうしたら|どうやって|方法を|教えてください|反映されない|表示されない|直し方|止め方)/;

/**
 * 引用の前に置かれた、短いお尋ねの一行。
 * ★お客様は、届いたご案内をまるごと引用して、その上に一言だけ書いて送られる。
 *   本文が長いので投稿文の貼り付けと判定され、
 *   「文章をお送りいただき、ありがとうございます」という的外れな返事になっていた
 *   （2026-09-06 ご質問 #13「このやり方がよくわかりません」＋Meta AI呼びかけの案内文まるごと）。
 */
const LEADING_ASK_RE = /(わかりません|分かりません|わからない|分からない|できません|できない|教えて|どうすれば|どうしたら|やり方|[?？])/;

/** 1行目だけが短いお尋ねで、その下は引用（＝ご依頼ではなくご質問）か。 */
export function hasLeadingAsk(t: string): boolean {
  const rows = t.split(/\r?\n/).filter((l) => l.trim());
  if (rows.length < 2) return false;
  const first = rows[0].trim();
  return Array.from(first).length <= 40 && LEADING_ASK_RE.test(first);
}

export function isPastedContent(t: string): boolean {
  const lines = t.split(/\r?\n/).filter((l) => l.trim()).length;
  if (hasLeadingAsk(t)) return false;
  // 絵文字（サロゲートペア）・記号・ハッシュタグ（サーバーのビルド対象がES5のため u フラグは使わない）
  const decorated = /[#＃]|[\uD83C-\uDBFF][\uDC00-\uDFFF]|[\u2600-\u27BF]|‼|⁉/.test(t);
  if (/[?？]/.test(t)) {
    // ★以前は「？が1つでもあれば投稿文ではない」としていた。しかし投稿文は
    //   読み手への問いかけで締めることが多い（「皆さんはどんな時に着てみたいと
    //   思われますか？」）。そのため呉服店様がご自身の投稿文を送り返されたとき、
    //   それがご質問として自動応答に回り、文中の「感じてほしい」に反応して
    //   「ご要望として承りました。夜の更新で反映します」と的外れな返事をしていた
    //   （2026-09-08 ご質問 #21）。
    //   飾りつき・複数行・60字以上のときだけ、？があっても投稿文とみなす。
    if (!(decorated && lines >= 3 && t.length >= 60)) return false;
    // 困りごとの言葉が入っていれば、投稿文ではなくご質問として扱う。
    if (SUPPORT_QUESTION_RE.test(t)) return false;
  }
  // ★3つ目の条件は、短めの投稿文が「ご質問」に紛れていたため足した。
  //   例：「富山市から10代から慢性肩こりの20代👩／“こんなに軽くなったことない〜！！”／
  //   全身ユルユルに…🥺／📍滑川市の…」＝約85字・4行・絵文字つき。
  //   これを質問として扱うと的外れな返事になり、担当者にも「質問」として上がる。
  return (t.length >= 150 && lines >= 3) || (t.length >= 120 && decorated) || (t.length >= 60 && lines >= 3 && decorated);
}

/**
 * 「ご質問」ではなく「ご依頼」のとき、その種類を返す。
 *
 * ★お客様が投稿の材料（実績・お客様のエピソード）を送ってこられたり、
 *   「こう投稿してほしい」と書かれることがある。これは質問ではないので、
 *   「お答えできないご質問でした」と返すと的外れになる。
 *   （2026-09-02、お客様が症例を3件送られたのに担当者送りになっていた）
 */
export function classifyRequestKind(t: string): "post" | "material" | "pasted" | null {
  if (isPastedContent(t)) return "pasted";
  // ★引用の上に「よくわかりません」と書かれたお尋ねは、引用の中の「投稿してください」に
  //   引かれて「投稿のご依頼」と判定されていた（2026-09-06 ご質問 #13）。
  if (hasLeadingAsk(t)) return null;
  // 「投稿してほしい」「告知したい」「ネタを作ってほしい」など
  if (/(投稿|告知|発信|ポスト|ネタ)[^。！？\n]{0,12}(したい|して|作|つくっ|つくり|書い|書き|出し|載せ|上げ|流し)/.test(t)
      || /(作っ|つくっ|書い|流し|載せ)[^。！？\n]{0,6}(ほしい|欲しい|ください|下さい|たい)/.test(t) && /(投稿|告知|発信|ポスト|ネタ)/.test(t)) return "post";
  // 実績・症例・お客様のエピソードらしい文章（体験の記述で、依頼の形をしていない）
  if (t.length >= 25 && /(来院|来店|患者|お客様|お客さん|施術|症状|改善|回復|復帰|卒業|通われ|いらっしゃ)/.test(t)
      && !/[?？]$/.test(t)) return "material";
  return null;
}

/**
 * 「今日の投稿をもう一度見たい」というご依頼か。
 *
 * ★以前は「投稿」と「見たい」の間を4字までしか見ておらず、ひらがなの「みたい」も
 *   拾えていなかった。そのため「今日の投稿をもう一度みたい」が自動応答に回り、
 *   「メニューから『今日の投稿』などをお選びください」とあいまいに答えるだけで、
 *   その場では見られなかった（2026-09-08 ご質問 #22）。
 *   投稿文の貼り付けを巻き込まないよう、短い一言のときだけ受ける。
 */
export function wantsTodayPosts(t: string): boolean {
  if (Array.from(t).length > 30) return false;
  return /^今日の投稿$/.test(t)
    || /(投稿|承認).{0,8}(確認|見たい|みたい|見る|みる|見せ|みせ|表示|もう一度)/.test(t);
}

/**
 * 「投稿を止めてください」＝しばらく自動投稿をお休みしたい、というご相談か。
 *
 * ★これまでは「停止」という言葉だけを見て、ご解約の案内に落としていた。
 *   お休みしたいだけの方に解約手続きの説明が届くのは、いちばん困る取り違えなので
 *   （2026-09-12 夜間整備のLINE全ボタン確認で検出）、投稿の話だと分かるものは
 *   設定（自動投稿を止める）へお通しする。
 *   ご本人が「解約」「退会」と書かれているときは、これまでどおり解約の案内に回す。
 */
export function wantsPausePosting(t: string): boolean {
  if (/(解約|退会)/.test(t)) return false;
  if (Array.from(t).length > 40) return false;
  return /(投稿|配信|自動投稿|ポスト)[^。！？\n]{0,8}(止め|止めて|停止|やめ|お休み|休ませ|ストップ)/.test(t);
}

/**
 * 「〇〇という言い方はやめてほしい」＝NGワードのご登録で解決するご要望か。
 *
 * ★以前は自動応答が「設定メニューから登録できます」と説明するだけで、
 *   お客様がもう一度メニューをたどる必要があった（2026-09-06 ご質問 #10）。
 *   その場で言葉の入力までお通しするために使う。
 */
export function wantsNgWord(t: string): boolean {
  return /(言い方|言葉|表現|ワード|フレーズ|話|ネタ)[^。！？\n]{0,10}(やめて|使わないで|書かないで|出さないで|入れないで|避けて|控えて)/.test(t);
}
