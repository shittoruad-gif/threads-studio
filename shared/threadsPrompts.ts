/**
 * Render the user's registered URLs into a prompt section that tells the
 * AI which one to embed for the requested post type.
 *
 * Rules:
 *  - 固定投稿 (pinned): always embed the LINE URL directly (safest place).
 *    If no LINE link, fall back to reservation URL.
 *  - オファー型 (offer): embed LINE or reservation URL in the CTA — but in
 *    a tree post (2段目以降), not the very first line.
 *  - その他: do NOT embed URLs directly. Refer the user to the固定投稿/
 *    プロフィール instead. Mentioning "プロフから△△へ" is fine.
 */
function formatLinksForPrompt(links: ProjectLinkLite[] | undefined, postType: PostType | undefined, preferredLinkType?: string, pinnedChannel?: string): string {
  if (!links || links.length === 0) return '';
  const lines: string[] = ['', '【登録済みの誘導先（チャネル）】'];
  for (const l of links) {
    const typeLabel = ({
      line: 'LINE公式', reservation: 'Web予約', website: '公式HP',
      instagram: 'Instagram', youtube: 'YouTube', other: 'その他',
    } as const)[l.type];
    // ★URL文字列は渡さない（本文へのURL混入を防ぐ）。チャネル名とラベルのみ。
    lines.push(`- ${typeLabel}（${l.label}）`);
  }

  // Per-type usage rule
  // ユーザーが固定投稿ウィザードで選んだ優先チャネルがあればそれを最優先
  const TYPE_LABEL: Record<string, string> = {
    line: 'LINE', reservation: 'Web予約', website: '公式HP',
    instagram: 'Instagram', youtube: 'YouTube', other: '登録先',
  };
  let cvChannel: string;
  if (preferredLinkType && links.some(l => l.type === preferredLinkType)) {
    cvChannel = TYPE_LABEL[preferredLinkType] ?? preferredLinkType;
  } else {
    const linePref = links.find(l => l.type === 'line');
    const reservationPref = links.find(l => l.type === 'reservation');
    const websitePref = links.find(l => l.type === 'website');
    // メインの誘導チャネル（LINE優先→Web予約→公式HP→先頭）
    cvChannel = linePref ? 'LINE' : reservationPref ? 'Web予約' : websitePref ? '公式HP'
      : TYPE_LABEL[links[0].type] ?? '登録先';
  }

  // ★方針A（教科書準拠）：本文・CTAに生URLは一切貼らず、プロフィール／固定投稿への間接誘導に統一する。
  lines.push('', '【誘導ルール（必須・教科書準拠）】');
  lines.push('- 投稿本文・CTA・ツリーのどこにも、生のURL（https://… 等）を絶対に貼らないこと。Threadsでは本文URLで到達が落ちるため。');
  lines.push(`- 主な誘導先は「${cvChannel}」。誘導は必ず「プロフィールのリンクから${cvChannel}へ」「固定投稿にまとめています」のような間接表現にする。`);
  lines.push(`- CTAには ${cvChannel} に進む"理由"（特典・得られるもの）をセットで書く。ただし特典はカウンセリング/入力にあるものだけ。無ければ「気軽にご相談ください」程度に留める。`);
  if (postType === 'pinned') {
    // ★案内先はお客様が登録したリンクで決まる（公式LINEとは限らない）。
    //   pinnedChannel が渡っていればその呼び名を使う（2026-09-04）。
    const pinnedCh = pinnedChannel || cvChannel;
    lines.push(`- 固定投稿でも本文にURLは貼らない。公開時にシステムが${pinnedCh}のURLをコメント欄（1件目の返信）に自動添付するので、本文は「コメント欄のリンクから」へ誘導する。`);
    lines.push(`- 締めの誘導は${pinnedCh}に合った言い方にする。登録されていない窓口（例：公式LINEが無いのに「LINEのご登録」）へ誘導しないこと。`);
  }
  lines.push('');
  return lines.join('\n');
}

