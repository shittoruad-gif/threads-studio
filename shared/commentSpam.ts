/**
 * 投稿に付いたコメントが「勧誘・出会い系・副業の誘い」かどうかの見分け。
 *
 * ★きっかけ：2026-09-17 ご質問 #37 梅原様
 *   「こちらのコメントは明らかな勧誘、出会い系的なコメントでしたので返信しませんでした。」
 *   こちらからお送りしたコメント返信カードには
 *   「この文で送る」「Threadsアプリで返信する」「文案を作り直す」の3つしかなく、
 *   **返信しないという選び方が無かった**。そのため梅原様は文章で状況を書いて送るしかなく、
 *   自動応答は答えられず（aiConfident=0）担当者送りになっていた。
 *
 *   さらに悪いことに、カードには勧誘コメント宛の「お礼と共感」の文案が入っていた。
 *   押せば勧誘アカウントへ返信してしまう。返信は相手への反応になるため、
 *   新しいアカウントほど停止の引き金になりやすい（docs/safe-operation-rules.md）。
 *
 * ここで勧誘と分かったものは、文案を作らず「返信しない」をおすすめするカードに変える。
 * 判定を変えるときは server/commentSpam.test.ts の実例も合わせて直すこと。
 */

/** これが入っていれば、それだけで勧誘・出会い系とみなす言葉。 */
const STRONG_RE = new RegExp(
  [
    // 出会い・アダルト
    "出会い系", "出会いたい", "セフレ", "裏垢", "パパ活", "ママ活", "援助交際", "援交",
    "ワンナイト", "大人の関係", "秘密の関係", "エッチ", "えっち", "18禁", "アダルト",
    "身体の関係", "会える子", "ヤリ",
    // ★「会いませんか」だけでは、お仕事のご挨拶（「一度お会いしませんか」）まで巻き込む。
    //   誘いの文脈が付いているときだけ勧誘とみなす（2026-09-19）。
    "(今夜|今から|これから|二人で|ふたりで|こっそり|飲みに|ホテル|近く)[^。！？\\n]{0,8}会(い|え)",
    // 副業・投資の勧誘
    "不労所得", "権利収入", "必ず稼", "絶対に稼", "絶対儲か", "確実に稼",
    "月収[0-9０-９]{2,}", "日給[0-9０-９]{2,}", "月[0-9０-９]{2,}万(円)?(稼|儲|収入)",
    "バイナリーオプション", "自動売買", "投資案件", "MLM", "ネットワークビジネス",
    "誰でも稼げ", "スマホ(だけ|1台|一台)で稼", "初期費用0円で稼",
    // 個人情報・外部誘導の釣り
    "LINE(を)?交換", "ライン交換", "ID追加", "id追加",
  ].join("|"),
);

/** 単体では弱いが、短い誘い文句と一緒なら勧誘とみなす言葉。 */
const BAIT_RE = new RegExp(
  [
    "プロフ(ィール)?(を)?(見|み)て", "詳(細|しく)は(DM|ディーエム|プロフ)", "DM(を)?(下|くだ)さい",
    "DM(を)?お待ち", "気軽にDM", "こっそり教え", "いい(お)?話", "おいしい話",
    "相互フォロー", "フォロバ(します|お願い)", "いいね返し", "フォロー返し",
  ].join("|"),
);

/** お金・稼ぎの話（BAIT と組み合わせて見る）。 */
const MONEY_RE = /(稼|儲|副業|投資|仮想通貨|ビットコイン|BTC|FX|案件|収入|報酬|高収入)/;

/**
 * このコメントは勧誘・出会い系か。
 *
 * ★お店への本当のお尋ね（「料金はいくらですか」「DMしました」など）を
 *   巻き込まないよう、言葉は絞ってある。迷ったら「勧誘ではない」に倒す
 *   （返信しないカードが出ても押さなければよいが、本物のお客様のコメントに
 *    「返信しないことをおすすめします」と出るほうが害が大きい）。
 */
export function looksLikeSpamComment(text: string, commenter?: string | null): boolean {
  const t = String(text || "").trim();
  if (!t) return false;
  if (STRONG_RE.test(t)) return true;
  // 釣り文句＋お金の話（例：「プロフ見てね！誰でもできる副業あります」）
  if (BAIT_RE.test(t) && MONEY_RE.test(t)) return true;
  // 相互フォロー系は、それだけで交流の価値がない（返信しても届く人は増えない）
  if (/(相互フォロー|フォロバ|いいね返し|フォロー返し)/.test(t) && Array.from(t).length <= 60) return true;
  // 名前そのものが出会い系の誘い（例：@deai_matching_bot）
  const name = String(commenter || "");
  if (/(deai|deaikei|papakatsu|sefure|adult|erolove|kasegu)/i.test(name)) return true;
  return false;
}
