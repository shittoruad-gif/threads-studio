-- 比嘉様からの「プロのセミナー価格からライトへ変えたい」をきっかけに分かったこと：
--  ・キャンペーン価格の契約は回数指定なしの普通の定期課金で、カードも保存されている。
--    金額はAPIで変えられる（通常価格への自動移行が本番で毎月それをやっている）。
--  ・それなのにプラン変更はキャンペーン価格を弾いていた。
--  ・さらに、プラン変更が呼ぶ univapay.updateSubscription は定期課金を解約するだけで
--    新しい課金を作っておらず、通していたら以後いっさい請求されない状態になっていた
--    （キャンペーン価格が弾かれていたため、実際に通った方は0件）。
--
-- 直したあとの形：プラン変更は「次回の請求から」に予約する。
-- 金額はUnivaPayの次回課金額を変えるだけ。機能は次の課金が通った時点で切り替える。
-- 下げる変更で、払った期間のうちに機能だけ減ることがなくなる。
