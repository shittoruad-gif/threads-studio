/** businessType に合う業種インサイトを返す（無ければ null） */
export function industryInsightFor(businessType: string | null | undefined): IndustryStyleInsight | null {
  const b = normalize(businessType ?? '');
  if (!b) return null;
  for (const ins of INDUSTRY_INSIGHTS) {
    if (ins.match.some((k) => b.includes(normalize(k)))) return ins;
  }
  return null;
}

/**
 * 生成プロンプトへ注入するセクションを組み立てる。
 * 該当業種が無ければ空文字（セクションごと出さない）。
 */
export function buildIndustryStyleSection(businessType: string | null | undefined): string {
  const ins = industryInsightFor(businessType);
  if (!ins) return '';
  const win = ins.win.map((l) => `- ${l}`).join('\n');
  const avoid = ins.avoid.map((l) => `- ${l}`).join('\n');
  return `

【この業種（${ins.label}）で実測されている勝ち筋・負け筋】
Threadsの${ins.label}の実投稿を反応数で分析した結果。事実ベースのルールの範囲内で従うこと。
効く書き方:
${win}
避ける書き方:
${avoid}`;
}
