import { describe, it, expect } from "vitest";
import { stripLinkMentions } from "./pinnedPostFlow";

/**
 * ご案内先URLを登録しないまま固定投稿を作ったとき、
 * 本文が「コメント欄のリンクから」と書いてしまうと、
 * 読んだ方が存在しないリンクを探すことになる。
 * 公開後にコメントを付けるのは案内先が登録されているときだけなので、
 * 案内先が無いときは本文からその一行を落とす。
 */
describe("案内先が無いときの固定投稿", () => {
  it("コメント欄のリンクへの誘導だけを落とし、本文は残す", () => {
    const post = [
      "倉敷市で肩こりにお悩みの方へ。",
      "",
      "当院は開業7年、のべ8000人の施術実績があります。",
      "",
      "ご予約やお問い合わせは、コメント欄のリンクからどうぞ。",
    ].join("\n");
    const out = stripLinkMentions(post);
    expect(out).not.toContain("コメント欄");
    expect(out).toContain("開業7年");
    expect(out).toContain("倉敷市で肩こりにお悩みの方へ。");
  });

  it("プロフィールのリンク・URLへの誘導も落とす", () => {
    // 実際の固定投稿は400〜470文字。誘導の一行だけが落ちる。
    const body = [
      "倉敷市で、デスクワークの肩こりにお悩みの方へ。",
      "",
      "強く押せば治る、と思っていませんか。原因は日々の姿勢にあることが多いです。",
      "当院は開業7年、のべ8000人の施術実績があります。",
      "国家資格者が、痛みの原因を丁寧にご説明しながら体を整えます。",
    ].join("\n");
    for (const line of [
      "詳しくはプロフィールのリンクからご覧ください。",
      "ご予約は下記のリンクからどうぞ。",
      "URLはこちらです。",
    ]) {
      expect(stripLinkMentions(`${body}\n\n${line}`)).toBe(body);
    }
  });

  it("リンクの話が無い投稿は、そのまま変えない", () => {
    const post = "倉敷市で肩こりにお悩みの方へ。\n\nお気軽にご相談ください。";
    expect(stripLinkMentions(post)).toBe(post);
  });

  it("本文の大半がリンクの話なら空を返す（作り直しになる）", () => {
    // 元の本文に戻すと、付かないリンクへの誘導が復活してしまう。
    const post = "コメント欄のリンクから。\nプロフィールのリンクから。\n短い本文。";
    expect(stripLinkMentions(post)).toBe("");
  });
});
