/**
 * お客様の口で書いた体験談（なりすましの口コミ）を止める（2026-10-22 夜間整備）。
 *
 * 事実：acc37（どい接骨院様）#4413。主題「運動指導」を入れる3回目の作り直しで、
 *   「八潮のどい接骨院で受けた運動指導が…深く実感しています」「私の身体の動かし方の癖や…教えてくれるんです」
 *   「…指導してもらえるのが素晴らしい点です」「…格段に向上しました」
 * と、通っている人が書いた口コミの形で下書きができた（ご本人が見送り・公開はされていない）。
 * お店のアカウントがお客様のふりをして感想を書くのは、作り話であり、医療・治療院の広告では体験談そのものが原則禁止。
 * 作り話チェック（AI）は1文ずつ見るため、文全体の「誰の口か」を取り違えたこの形を拾えなかった。
 *
 * 決まった言い回しだけで見る（通信しない）。店主の口でも出る言い回し（「他院で受けた施術で…」「知ってもらえたら」）が
 * 1つあるだけでは止めないよう、種類の違う印が3つ以上そろったときだけ「お客様の口」とする。
 */

const SIGNALS: Array<{ label: string; re: RegExp }> = [
  // 受け手として、お店で受けたものを語る
  { label: "お店で受けた", re: /(で|に)受けた(施術|指導|運動指導|治療|マッサージ|カウンセリング|レッスン|整体|ケア|トレーニング|アドバイス)/ },
  // お店（の人）が自分にしてくれる
  { label: "してくれる", re: /(教えて|見て|説明して|施術して|指導して|聞いて|ほぐして|整えて)くれ(る|た|ます|ました|るんです|たんです)/ },
  // お店（の人）にしてもらえる
  { label: "してもらえる", re: /(教えて|見て|説明して|施術して|指導して|聞いて|ほぐして|整えて)もら(える|えた|えます|えました|いました|って)/ },
  // 書き手自身の体
  { label: "私の体", re: /(私|わたし|自分)の(身体|体|からだ|腰|膝|肩|首|姿勢|動かし方)/ },
  // 書き手自身の効果の実感
  { label: "実感している", re: /(実感して(い|おり)ます|実感しました|実感中|実感しています)/ },
  // 書き手自身の変化（「〜しました」で言い切る）
  { label: "良くなりました", re: /(格段に|すっかり|かなり|本当に)?(向上しました|楽になりました|変わりました|良くなりました|改善しました|軽くなりました)/ },
  // 第三者として褒める
  { label: "素晴らしい点", re: /(素晴らしい点|ここがすごい|さすが(です|だと))/ },
];

export interface CustomerVoiceResult {
  ok: boolean;
  /** そろった印（ログと作り直しの理由に使う） */
  hits: string[];
}

/** 種類の違う印が3つ以上で「お客様の口で書いた体験談」とみなす */
export const CUSTOMER_VOICE_MIN_SIGNALS = 3;

export function checkCustomerVoice(text: string): CustomerVoiceResult {
  const t = String(text || "").replace(/\s+/g, "");
  // かぎかっこの中（お客様の言葉の引用）は、店主が紹介しているだけなので数えない
  const outside = t.replace(/「[^」]{0,80}」/g, "");
  const hits = SIGNALS.filter((s) => s.re.test(outside)).map((s) => s.label);
  return { ok: hits.length < CUSTOMER_VOICE_MIN_SIGNALS, hits };
}

/** 作り直しのときに渡す理由 */
export function customerVoiceRetryHint(hits: string[]): string {
  return `- 通っているお客様が書いた口コミの形（${hits.join("・")}）になっている。お客様のふりをして感想を書かない。` +
    "お店の側（店主・院長・スタッフ）の口で、何をしているか・どんな方に向いているかを書く。";
}
