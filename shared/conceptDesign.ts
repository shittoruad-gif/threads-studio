同業だけを競合と見ない。代替手段（脱毛サロンに対する家庭用脱毛機）、無料情報（検索・YouTube・AI）、「何もしない」という選択、顧客がその時間を使っている対象すべてを競合として扱う。顧客が普段何に時間を使っているか（Instagramのおすすめ欄・検索履歴・YouTube視聴傾向）を把握する。

