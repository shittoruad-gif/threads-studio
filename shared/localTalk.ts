/**
 * 「地元の会話」の投稿（切り口 local_talk・2026-10-18 三上様「普段の投稿やスレッドスタジオにもこれを活かして」）。
 *
 * 実データ（Moveact 玉島・直近45日）：
 *  - 店主が手で書いた、地元の人への小さな問いかけが大きく見られ、返信も付いた。
 *      「雨降ってますが、今日玉島まつりはあるんですかね？💦」        5,587表示・返信15
 *      「新倉敷・玉島の名産品と言えば？ 地元の方のおすすめも…」      4,222表示・返信25
 *      「倉敷・新倉敷・玉島周辺の方！ 産後ダイエットモニターを…」   1,741表示・返信14
 *      「新倉敷・玉島のみなさん おはようございます☀」                 753表示・返信10
 *    （他院：「ちょこっとウチナーグチ『リバテープ』=絆創膏…皆様の地域はどうでしょうか」658表示・返信8）
 *  - AIで作った投稿は平均約108表示・2,889本のうち返信が1件でも付いたのは183本だけ。
 *  - 三上様の直し：広告っぽい → AIっぽい・不自然 → 「もっと人間味」 → 「絵文字も適宜」 → 次の形で「かなりいい感じ」：
 *      「鴨方のそうめん、冬でも食べる派ですか？笑」「浅口の人に聞きたいんですけど、肩こったとき『はる』って言います？」
 *      「寝るとき横向きの人ー！ 朝起きたら肩バキバキになってません？」
 *
 * 決まり（プロンプト localTalkNote と、出来上がりの検査 angleGuard の local_talk）：
 *  - 地元の人に、町のこと（食べ物・場所・季節の地元のこと・方言・暮らしのあるある）を話しかける
 *  - 一言で答えられる小さな質問で終える（会話型と同じく問いかけの締めを許す）
 *  - 話し言葉・少し崩す・絵文字は「ときどき」（毎回入れない・最大2個）
 *  - 宣伝の言葉・「〜な人へ」・「国家資格者が〜」・効果の話・URL は書かない。短い（多くは60字以内）
 *  - その日の出来事・イベント・天気は言い切らない（確かめられない）。日付が変わっても通じる話題だけ
 *
 * 割合はここだけで変える（0 にすれば止まる・夜間に反映）。
 */

