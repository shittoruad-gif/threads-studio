/**
 * businessType 文字列から該当する業界規制ブロックを返す。
 * ヒットしなかった場合は空配列。共通規制は別途常に適用される。
 */
export function detectIndustryRegulations(
  businessType: string | undefined | null,
): IndustryRegulationBlock[] {
  if (!businessType) return [];
  const norm = String(businessType).toLowerCase();
  const matched: IndustryRegulationBlock[] = [];
  const seen = new Set<string>();
  for (const m of INDUSTRY_MATCHERS) {
    if (m.keywords.some((k) => norm.includes(k.toLowerCase()))) {
      if (!seen.has(m.block.label)) {
        matched.push(m.block);
        seen.add(m.block.label);
      }
    }
  }
  return matched;
}

/**
 * 業界判定 + 共通ルールを結合し、プロンプトに差し込めるテキストブロックを生成。
 *
 * - 業界がヒットしなかった場合は共通ルールのみ
 * - すべて「★絶対NG」「✏ 推奨置換」「⚠ 注意」の3節構成で AI が読みやすく整形
 */
export function buildAdRegulationsPromptSection(
  businessType: string | undefined | null,
): string {
  const blocks = [COMMON_REGULATION, ...detectIndustryRegulations(businessType)];
  const lines: string[] = [
    '',
    '【★最優先：広告規制ルール（法令ベース・例外なく厳守）】',
    'このセクションのNG表現は、ユーザー入力やカウンセリング結果に書かれていても、AIが投稿に出さないこと。',
    '法令違反は事業者本人の責任になるが、生成側で先回りして避ける。',
    '',
  ];

  for (const b of blocks) {
    lines.push(`■ ${b.label}（根拠: ${b.laws.join(' / ')}）`);
    if (b.absoluteNg.length > 0) {
      lines.push('  ★絶対NG（投稿に1つでも入れない）:');
      b.absoluteNg.forEach((n) => lines.push(`    ・${n}`));
    }
    if (b.replacements.length > 0) {
      lines.push('  ✏ 推奨置換（左 → 右に書き換える）:');
      b.replacements.forEach((r) => {
        const reason = r.reason ? `（${r.reason}）` : '';
        lines.push(`    ・「${r.ng}」 → 「${r.ok}」${reason}`);
      });
    }
    if (b.cautions.length > 0) {
      lines.push('  ⚠ 注意:');
      b.cautions.forEach((c) => lines.push(`    ・${c}`));
    }
    lines.push('');
  }

  lines.push('【規制ルールの最終チェック手順】');
  lines.push('  1. 投稿の本文・CTA・ツリー全てを書き終えたら、上の「★絶対NG」リストに該当する語が混入していないか自分で点検する');
  lines.push('  2. 「✏ 推奨置換」に該当する語があれば右側の表現に書き換える');
  lines.push('  3. 数字を出すときは、入力情報・カウンセリング結果に明記されているものだけ使う');
  lines.push('  4. 体験談・ビフォーアフターは、業界によっては原則禁止。出すなら「個人の感想・効果には個人差があります」のニュアンスを必ず添える');
  lines.push('');

  return lines.join('\n');
}

/**
 * 生成後の投稿文を NG キーワードで簡易スキャン。違反があれば理由付きで返す。
 * （UI側で警告を出すのに使える。AI には入れない。）
 */
export interface RegulationViolation {
  category: string;
  matched: string;
  reason?: string;
}

export function scanForRegulationViolations(
  text: string,
  businessType: string | undefined | null,
): RegulationViolation[] {
  const violations: RegulationViolation[] = [];
  const blocks = [COMMON_REGULATION, ...detectIndustryRegulations(businessType)];
  const norm = text.toLowerCase();
  for (const b of blocks) {
    for (const r of b.replacements) {
      // 単純な部分一致（誤検知はあるが、警告のみ）
      const ngLower = r.ng.toLowerCase();
      // 括弧書き内の補足は除外して照合
      const stripped = ngLower.replace(/[（(].*?[)）]/g, '').trim();
      if (stripped && norm.includes(stripped)) {
        violations.push({ category: b.label, matched: r.ng, reason: r.reason });
      }
    }
  }
  return violations;
}
