/**
 * 登録に無い「見てきたような町・世の中の様子」の言い切りを止める（2026-11-27 三上様
 * 「クリスマスの飾りとか書いてますが、飾られてない場合あるんじゃないですか？事実と異なる事は入れないとこちらも言っています」）。
 *
 * 指示文（shared/localTalk.ts）には「その日の出来事・天気を言い切らない」「登録に無い地元のお店・数字を書かない」があったが、
 * 「最近〜が増えてきました」のような町の様子の言い切りは機械の検査が無く、すり抜けていた。
 *   acc10 #7745「玉島中央町を歩くと、お店の軒先に飾られたクリスマスの飾りが増えてきました。」
 *   acc38 #7789「本格的な寒さで、腰の痛みが気になる方が増えています。」（数えていない「増えている」）
 *   acc43 #7800「倉敷駅近くにオープンしたお店です。」（登録に開店の時期が無い）
 *   直近30日の公開済みの地元の会話 360本のうち約1割に同じ形の言葉。
 * 問いかけの文（「最近見かけるようになったものありますか？」）は聞いているだけなので止めない。
 * 同じ言葉がお店の登録に書かれていれば止めない（ご本人が書いた事実）。
 */
// ★「増えております」（敬語の同じ形）も拾う（2026-11-27 夜間整備：acc37 #7380「…と感じる方が増えております。」が公開済み）
const OBSERVATION = /増えて(き|い|お)|増えました|増加して|見かけるようにな|飾(られ|り)|イルミネーション|ツリーが|咲(い|き)(て|始)|色づ|紅葉が|始まりました|オープンし|新しくでき|できましたね|賑わ|にぎわ|行列|見頃|渋滞|工事中|混んで(い|ま)|匂いがし|香りがし/;

/**
 * 11/27 金光で追加：天気・季節の言い切り（「金光の夜はもうすっかり冷えますね」）と、
 * 確かでない名物の言い切り（「金光の秋といえば、やっぱり柿ですよね」）。
 */
const WEATHER_OR_FAMOUS = /すっかり冷え|冷えますね|冷えてきました|寒くなりました|寒くなってきました|暑くなってきました|気持ちいい季節ですね|といえば、?やっぱり/;
/**
 * お店の設備・できることの言い切り（「金光駅から近いので、着替えを持ってきても大丈夫ですよ」）。
 * 店頭で何ができるかは、登録に書かれているときだけ書く（三上様の決まり）。
 */
const STORE_FACT = /駅から(近|すぐ|徒歩)|駐車場(あり|が|も|は)|着替え|更衣室|キッズスペース|キッズルーム|個室|シャワー|ベビーカー/;

/** 文に分ける（。！!？?・改行） */
function sentences(text: string): string[] {
  return String(text ?? "").replace(/\r/g, "").split(/(?<=[。！!？?])|\n/).map((s) => s.trim()).filter(Boolean);
}

/**
 * 登録に無い様子の言い切りがあれば、その文を返す（なければ null）。
 * registered：お店の登録の文（強み・実績・こだわり・地域・ネタ帳など）をつないだもの
 */
export function unverifiedObservation(text: string, registered: string): string | null {
  const reg = String(registered ?? "");
  for (const s of sentences(text)) {
    if (/[？?]\s*$/.test(s)) continue; // 問いかけは聞いているだけ
    for (const re of [OBSERVATION, WEATHER_OR_FAMOUS, STORE_FACT]) {
      const m = s.match(re);
      if (!m) continue;
      // 登録に書かれている事実は止めない（「駐車場あり」「キッズルーム完備」など）
      const key = m[0].replace(/^駅から.*/, "駅").replace(/^駐車場.*/, "駐車場");
      if (reg.includes(m[0]) || (key !== m[0] && reg.includes(key) && re === STORE_FACT)) continue;
      return s;
    }
  }
  return null;
}
