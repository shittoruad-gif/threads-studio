/** 今日（JST）その方に送る個別のお知らせ */
export function personalNoticesFor(userId: number, now: number = Date.now()): PersonalNotice[] {
  const jst = new Date(now + 9 * 3600 * 1000).toISOString().slice(0, 10);
  return PERSONAL_NOTICES.filter((n) => n.sendOn === jst && n.userId === userId);
}

/** 今日（JST）個別のお知らせがある方の userId */
export function personalNoticeUserIds(now: number = Date.now()): number[] {
  const jst = new Date(now + 9 * 3600 * 1000).toISOString().slice(0, 10);
  return Array.from(new Set(PERSONAL_NOTICES.filter((n) => n.sendOn === jst).map((n) => n.userId)));
}
