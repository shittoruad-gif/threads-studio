/**
 * プロンプトに渡す地名（登録の地域を市区町村に分けたもの＋承認済みの地元の言葉）。
 * identityGuard の「この店を指す言葉」と同じ考え方（都道府県だけは弱いので外す）。
 */
export function localTalkPlaces(area: string | null | undefined, localTerms?: string | null): string[] {
  const out: string[] = [];
  const add = (s: string) => {
    const t = s.replace(/\s+/g, '').trim();
    if (Array.from(t).length < 2 || Array.from(t).length > 10) return;
    if (/^(なし|無し|未定|特になし|オンライン.*|全国.*)$/.test(t)) return;
    if (/[0-9０-９]|徒歩|から|車で|より/.test(t)) return; // 「JR新倉敷駅から車で約7分」のような道案内は地名に入れない
    if (!out.includes(t)) out.push(t);
  };
  const a = String(area || '').replace(/\s+/g, '');
  const parts = a.split(/(?<=[都道府県市区町村郡])/).filter(Boolean);
  for (const p of parts) {
    if (/[都道府県]$/.test(p) && parts.length > 1) continue;
    const bare = p.replace(/[市区町村郡]$/, '');
    add(Array.from(bare).length >= 2 ? bare : p);
  }
  for (const t of String(localTerms || '').split(/[、,\/／\s　\n・]+/)) add(t.replace(/駅$/, ''));
  return out.slice(0, 6);
}

/**
 * 生成プロンプトの末尾に付ける「地元の会話の回」の決まり（長さ・絵文字・締めの共通指示より優先）。
 * places が空なら呼ばない（地域の無いお店では使わない）。
 */
/**
 * 直近の投稿のうち「季節の食べ物」を聞いた短い投稿を1本返す（無ければ null）。
 *
 * 2026-11-20 夜間整備：同じ日に同じ問いかけが2本並んでいた。
 *   acc34 #7319「岐阜の秋といえば、やっぱり美味しいものが…一番食べたくなるものって何ですか？」
 *         #7321「岐阜の秋といえば、やっぱり富有柿ですよね。…どんな食べ方が好きですか？」（同じ日・2日前にも柿）
 *   acc33 #7295「横須賀中央の秋といえば、何を思い浮かべますか？」 #7297「川崎の秋といえば、やっぱり梨や柿ですよね」（同じ日）
 *   使い回しの検査は、地名を外すと「の秋といえばやっぱり」（漢字1字）しか残らず、決まり文句扱いで通していた。
 *   話題は5種類あるのに「食べ物・季節」に寄るため、直近で出していたら今回は別の種類を指定する（作り直しはしない＝枠を減らさない）。
 */
export function recentSeasonFoodTalk(recentPosts: readonly string[] | null | undefined): string | null {
  const RE = /[春夏秋冬](?:の味覚|といえば|の楽しみ)|この(?:季節|時期)[^。？?]{0,14}(?:食べ|楽しみ)|食べたくな|食べすぎ|食べとかないと|旬の(?:食べ物|もの)/;
  for (const p of recentPosts ?? []) {
    const t = String(p ?? '').replace(/\s+/g, ' ').trim();
    // 地元の会話は短い（長くても90字）。長い投稿の中の一言は別の話なので数えない
    if (!t || Array.from(t).length > LOCAL_TALK.hardMax + 20) continue;
    if (RE.test(t)) return t;
  }
  return null;
}

/**
 * 直近の投稿のうち「地元の会話」の形（短い・問いかけで終わる）のものを新しい順に返す（最大 max 本）。
 *
 * 2026-11-21 夜間整備：同じ日に同じ話題の地元の会話が2本並んでいた（朝の生成は1日分を続けて作る）。
 *   acc36 #7369「…『そろそろコタツ出す？』って返ってくるのは、あるあるだと思う。」 #7378「岡山も朝晩は冷えるね。コタツはもう出した？」
 *   acc24 #7359「廿日市もすっかり秋の深まりを感じますね。」 #7361「廿日市もすっかり秋ですね。」
 *   acc40 #7387「運転中、つい口ずさんでしまう曲ってありますか？」 #7389「矢掛の道って、運転中につい『あるある』って思う瞬間…」
 *   直近の投稿は上の【直近の投稿】で渡してあるが、お店の投稿に混ざって埋もれ、同じ物・同じ場面に戻っていた。
 *   地元の会話の決まりの中で「もう使った話」として名指しする（作り直しはしない＝枠は減らさない・ガードは変えていない）。
 */
export function recentLocalTalks(recentPosts: readonly string[] | null | undefined, max = 4): string[] {
  const out: string[] = [];
  for (const p of recentPosts ?? []) {
    const t = String(p ?? '').replace(/\s+/g, ' ').trim();
    if (!t || Array.from(t).length > LOCAL_TALK.hardMax + 20) continue;
    // 地元の会話は問いかけ・同意・「あるある」で終える（#7381「…急いでるとやっちゃいますよね😅」）。
    // 短いだけのお店の投稿（「車検は2か月前から受けられます😊」）は数えない
    if (!/[?？]|教えて|あるある|よね|かな|笑/.test(t)) continue;
    if (!out.includes(t)) out.push(t);
    if (out.length >= max) break;
  }
  return out;
}

export function localTalkNote(opts: { places: readonly string[]; allowEmoji: boolean; recentSeasonFood?: string | null; recentTalks?: readonly string[] | null }): string {
  const places = opts.places.length ? opts.places.map((p) => `「${p}」`).join('') : '登録の地域';
  const emoji = opts.allowEmoji
    ? '絵文字は「ときどき」。入れない回のほうが多くてよい。入れるなら1〜2個まで（上の「絵文字を1〜3個、毎回」の指示よりこちらを優先）。'
    : '絵文字は使わない。';
  const avoidFood = opts.recentSeasonFood
    ? `- ★直近で「季節の食べ物」をもう聞いている（「${Array.from(opts.recentSeasonFood.replace(/[〇○◯]{2,}/g, '…')).slice(0, 60).join('')}」）。今回は食べ物・味覚・季節の話にしない。「〜の秋（冬）といえば」でも始めない。身近な場所や景色／方言・言い方の違い／暮らしのあるある のどれかで書く。\n`
    : '';
  const talks = (opts.recentTalks ?? []).filter(Boolean);
  const avoidSame = talks.length
    ? `- ★直近の「地元の会話」はこれ（${talks.map((t) => `「${Array.from(t.replace(/[〇○◯]{2,}/g, '…')).slice(0, 50).join('')}」`).join('')}）。ここに出てくる物・場面・季節の言い方と同じ話をもう一度書かない。書き出しも変える。上の話題の種類のうち、これらと違う種類から選ぶ。\n`
    : '';
  return `

【今回は「地元の会話」の回（ここまでの長さ・1行目・絵文字・締めの指示より優先・厳守）】
お店の宣伝ではなく、地元に住む人に話しかける、ふだんのつぶやきを1つだけ書く。店主が自分のスマホで、ふと打ったような文にする。
（実測：このアプリのお店で、店主が手で書いた「地元の人への小さな問いかけ」はAIの投稿より桁違いに見られ、返信も多く付いた。）
- 話題は次のどれか1つ：地元の食べ物・名物／地元の身近な場所や景色（川・海・駅・通り・公園など）／この季節の地元のこと／方言・言い方の違い／暮らしのあるある（家事・仕事・寝るとき・運転など、だれにでもあるちょっとした場面）。
${avoidFood}${avoidSame}- 地名（${places}のどれか）は、話の中身として自然なときだけ1回入れる。「（県名）、秋の夜長に何してます？」のように地名を頭に付け足すだけの形はしない。地元の食べ物・場所の名前そのものが地名になっていればそれで十分（10/26 三上様「地域名を無理やり入れて不自然」）。
- 最後は、地元の人が一言で答えられる具体的な小さな質問で終える（形の例：「〜派ですか？」「〜って言います？」「〜ですかね？」「〜教えてください」）。
- 長さは${LOCAL_TALK.targetMin}〜${LOCAL_TALK.targetMax}字（長くても80字）。1〜3行。説明・理由・オチ・締めの挨拶は足さない。
- 話し言葉で、きれいに整えすぎない。「…」「笑」「ー！」のような、人が打つ崩しを1つ入れてよい。
- ${emoji}
- 書かないこと：お店の名前・メニュー・施術・予約・料金・営業時間・「〜な人へ」・「国家資格」・体が良くなる／効果の話・宣伝の言葉・URL・ハッシュタグ。
- 書かないこと：「今日はお祭りがある」「今日は雨」のような、その日の出来事・イベント・天気の言い切り（確かめられないため）。日付が変わっても通じる話題にする。
- 地元の名物・場所・方言は、広く知られていて確かなものだけ。自信がなければ「〜の名物といえば何ですか？」のように相手に聞く形にして、自分では言い切らない。登録に無い地元のお店の名前・人の名前・数字は書かない。
- 書き手自身や家族の体験・過去は作らない（「うちの子が」「昔の私は」「私だけ？」など）。自分が最近したことの報告（「ついにコタツ出しちゃいました」「〜食べてきました」「〜行ってきました」）も作らない。自分の話はせず、相手に聞くだけにする。
- 「〇〇」「○○」のような伏せ字・空欄は一切書かない（「私はやっぱり〇〇かな」「やっぱり〇〇！」は使えない）。名前を知らないものは、名前を出さずに質問だけで終える。「私はやっぱり、あの懐かしいメロディですね」「私はあの角を曲がる時ですね」のように、「あの〜」「例の〜」と名前を伏せた自分の答えも書かない。「やっぱりアレですよね」「あの甘い香り」「あのカーブ」のように、名前を言わずにぼかす言い方もしない（読む人には何のことか分からない）。
- 「〜いませんか？」「〜と思いませんか？」「〜ですよね？」の形は使わない。「〜とは？」「何でしょう？」のように答えを伏せて終えない。
- 形の参考（言い回し・話題はそのまま使わない。この地域の話に置きかえる）：「（地名）の（食べ物）、（季節）でも食べる派ですか？笑」／「（地名）の人に聞きたいんですけど、（方言の言い方）って言います？」／「（だれにでもある場面）の人ー！ （ちょっとした体のこと）になってません？」`;
}

/**
 * 「私はあの川沿いの道が好きです」のように、名前を伏せたまま自分の答えを言う文を落とす（地元の会話だけ）。
 *
 * 2026-11-22 夜間整備：11/20 に伏せ字「〇〇」を止めてから、代わりに「あの〜」で伏せる形が増えた
 *   （地元の会話のうち 11/21 12本中3本・11/22 18本中5本。11/9〜11/20 は 116本中3本）。11/21 に指示文へ足したが止まらなかった。
 *     #7438「…夜の散歩が気持ちいい場所ってどこでしょう？／私はあの川沿いの道が好きです。」
 *     #7444「岡山って、冬支度何から始めますか？／私はまず、あの温かい飲み物からですね。」
 *     #7447「…思わず目を奪われる景色ってありますか？／私はあの、夕焼けに染まる川沿いの道が好きです。」
 *     #7387「…口ずさんでしまう曲ってありますか？／私はやっぱり、あの懐かしいメロディですね。」 #7389「私はあの角を曲がる時ですね。」
 *   どれも質問のあとに付けた一文で、決まりは「自分の話はせず、相手に聞くだけ」。その一文を落とせば決まりどおりの文になる
 *   （事実は増えない・作り直さない＝枠は減らない）。落としたあとに問いかけが残らないときは触らない。
 */
export function stripVagueSelfAnswer(text: string): string {
  const src = String(text ?? '');
  const RE = /(?:^|(?<=[。！!？?\n]))[ \t　]*(?:私|わたし|僕|ぼく|うち)は[^。！!？?\n]{0,10}(?:あの|例の|アレ)[^。！!？?\n]{0,30}(?:です|ます|かな|だな)[ねよ]?[。！!]?(?:[ \t　]*(?:[\u2600-\u27BF]|[\uD800-\uDBFF][\uDC00-\uDFFF])\uFE0F?)*[ \t　]*(?=\n|$)/g;
  if (!RE.test(src)) return src;
  RE.lastIndex = 0;
  const out = src.replace(RE, '').replace(/\n{3,}/g, '\n\n').trim();
  if (!/[?？]|教えて/.test(out) || localTalkLength(out) < 10) return src;
  return out;
}

/**
 * 名前を伏せた言い方（「あの、雪が降る前にやるアレ、もう済ませましたか？」「ついあの道の横道に…」）を見つける。無ければ null。
 *
 * 2026-11-22 夜間整備：#7412（acc16）・#7425（acc24）。読んだ人には何のことか分からず、答えようがない。
 *   - 「アレ」のあと名前を言わないまま質問している（「やっぱりアレですよね。／香箱ガニ、もう食べましたか？」は後で名前を言うので当てない）
 *   - 書き出しの文の「あの＋場所・物」（前に指すものが無い。「金木犀の香り。あの香りがすると…」は前の文を指すので当てない）
 *   直近120日の公開済みの地元の会話で当たるのは8本（#6411・#6624・#6734・#7412・#7425 ほか）。作り直しの理由に使う（最後の作り直しでは公開する＝枠は減らさない）。
 */
export function findVagueName(text: string): string | null {
  const t = String(text ?? '').trim();
  // 「コアレ」「アレルギー」のような言葉の一部は数えない
  const are = t.match(/(?<![ァ-ヶー])アレ(?![ァ-ヶー])[、,]?[^。\n「『]{0,14}[?？]/);
  if (are) return are[0];
  const first = t.split(/[。！!？?\n]/).map((x) => x.trim()).find(Boolean) ?? '';
  const ano = first.match(/(?:あの|例の)(?:道|通り|橋|川|坂|角|店|場所|公園|景色|味|匂い|香り|音|曲|メロディ|飲み物|食べ物)[^、。]{0,8}/);
  return ano ? ano[0] : null;
}

/** 名前を伏せた言い方で作り直すときに渡す一言 */
export function vagueNameRetryHint(found: string): string {
  return `前の案は「${found}」と名前を伏せた言い方で、読んだ人には何のことか分からない。「あの〜」「例の〜」「アレ」を使わない。広く知られた物の名前（こたつ・おでん・みかん など）をそのまま書くか、名前を出さずに「どこですか？」「何ですか？」と相手に聞くだけにする。`;
}

/** 本文の字数（空白を除く） */
export function localTalkLength(text: string): number {
  return Array.from(String(text ?? '').replace(/\s+/g, '')).length;
}

/** このお客様は地元の会話を作らない方か */
export function localTalkOptedOut(userId: number | null | undefined): boolean {
  return userId != null && LOCAL_TALK.optOutUserIds.includes(Number(userId));
}

/**
 * お客様が書き方の決まりで「地元の投稿はいらない」と決めているか（2026-10-21 お知らせ：
 * 「止めたいときは『決まり：地元の投稿はいらない』と送ってください」）。アカウントごと・コードの書き換えなしで止まる。
 */
export function localTalkOptedOutByRules(rules: readonly string[] | null | undefined): boolean {
  return (rules ?? []).some((r) => /(地元|地域)/.test(r) && /(いらない|要らない|不要|作らない|つくらない|止め|やめ|出さない|書かない|なし|無し)/.test(r));
}
