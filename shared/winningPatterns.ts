/**
 * 業種に合う「伸びる型」だけを返す。合うものが無ければ空文字。
 * 空文字のときは、プロンプトにこのセクション自体が入らない。
 */
export function buildWinningPatternSection(businessType: string | null | undefined): string {
  const t = String(businessType || '').trim();
  if (!t) return '';
  const hit = WINNING_PATTERNS.find((p) => p.match.some((m) => t.includes(m)));
  if (!hit) return '';
  return [
    '',
    '【この業種で伸びている投稿の型（実際にThreadsで反応のある型）】',
    '丸パクリではなく、自分の言葉に置き換えて使うこと。',
    '',
    hit.title,
    hit.body,
    '',
  ].join('\n');
}
