/**
 * 業界別 広告規制ガイドライン（2024〜2025年版）
 *
 * 目的: SNS（特にThreads）投稿で違反しがちな表現を「業界の現行法に基づいて」
 *       AI生成側で先回りして禁止する。
 *
 * 設計:
 *  - businessType 文字列からキーワード判定で該当業界を割り出す
 *  - 業界ごとに「絶対NG」「条件付きNG」「推奨置換」をリスト化
 *  - 全業種共通ルール（ステマ規制・景表法のNo.1表示等）は常に適用
 *  - プロンプトに差し込むときは、業界該当ぶん + 共通ぶん を結合
 *
 * 出典:
 *  - 景品表示法（不当景品類及び不当表示防止法）
 *  - 景品表示法 ステマ規制（令和5年10月1日施行）
 *  - 薬機法（医薬品、医療機器等の品質、有効性及び安全性の確保等に関する法律）
 *  - 医療法 / 医療広告ガイドライン（平成30年6月改訂）
 *  - あはき法（あん摩マツサージ指圧師、はり師、きゆう師等に関する法律）
 *  - 健康増進法 / 食品表示法
 *  - 不動産公正競争規約
 *  - 特定商取引法（令和4年6月改正・令和5年6月施行）
 *  - 弁護士法 / 司法書士法 / 税理士法 等の士業広告規制
 *  - 金融商品取引法 / 貸金業法
 *  - JAS法 / 健康増進法
 */

export interface IndustryRegulationBlock {
  /** 業界の表示名 */
  label: string;
  /** 該当法令（プロンプトに明示する根拠） */
  laws: string[];
  /** 絶対NG表現（投稿に1個でも入ったら違反） */
  absoluteNg: string[];
  /** 推奨置換（NG → OK） */
  replacements: { ng: string; ok: string; reason?: string }[];
  /** 条件付き / 注意喚起 */
  cautions: string[];
}

