/**
 * 業種別の勝ち筋・負け筋（Threads実投稿の定点リサーチ由来）。
 *
 * データの出どころ:
 *   Threads公開検索から業種ごとに発信者（店舗・事業者）側の実投稿を収集し、
 *   いいね数で高反応/低反応に分けて共通パターンを抽出したもの。
 *   初回リサーチ 2026-08-28（10業種・発信者投稿約150本）。
 *   コーパス原文と集計は docs/research/ に保存している。
 *
 * 観客フィルタ（2026-08-28 三上さん指示）:
 *   「伸びた」だけでは採用しない。いいねの出どころが同業の共感・情である型
 *   （同業あるある・経営の弱音の吐露・作家仲間の相互応援など）は、
 *   反応数が大きくても win に載せない。載せるのは「見込み客に届き、
 *   来店・注文・問い合わせ・プロフィール遷移につながる根拠がある型」だけ。
 *   同業向けの型は avoid 側に「同業には伸びるが集客に直結しない」と明記する。
 *
 * 運用ルール:
 *   - ここの文言は生成プロンプトにそのまま注入される。**実在の投稿の文言を
 *     コピーして書かない**（AIがその文言を投稿に流用する事故が実際に起きた）。
 *   - 根拠のない一般論を足さない。リサーチで観察された事実だけを書く。
 *   - 週次の定期リサーチ（scheduled-task: weekly-jp-style-research）が
 *     新しいコーパスで検証・更新する。エントリを増やすときは match の
 *     キーワード衝突に注意（先勝ち）。
 */

export interface IndustryStyleInsight {
  id: string;
  /** 表示用の業種名 */
  label: string;
  /** projects.businessType に含まれていたら適用するキーワード（正規化後の部分一致） */
  match: string[];
  /** この業種で効く書き方（実測由来・抽象的な指示のみ） */
  win: string[];
  /** この業種で避ける書き方（実測由来） */
  avoid: string[];
}

function normalize(s: string): string {
  return (s || '')
    .toLowerCase()
    .replace(/[Ａ-Ｚａ-ｚ０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
    .replace(/\s+/g, '');
}

