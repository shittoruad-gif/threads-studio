/** 切り口の説明（postAngles の hint・angleNote に入る） */
export const LOCAL_TALK_HINT =
  'お店の宣伝ではなく、地元に住む人へ町のこと（地元の食べ物・身近な場所・この季節の地元のこと・方言・暮らしのあるある）を話しかける、短いつぶやき。'
  + '最後は地元の人が一言で答えられる小さな質問で終える。お店の名前・メニュー・予約・効果の話は書かない。詳しい決まりは末尾の【地元の会話の回】に従う。';

/**
 * プロンプトに渡す地名（登録の地域を市区町村に分けたもの＋承認済みの地元の言葉）。
 * identityGuard の「この店を指す言葉」と同じ考え方（都道府県だけは弱いので外す）。
 */
export function localTalkPlaces(area: string | null | undefined, localTerms?: string | null): string[] {
  const out: string[] = [];
  const add = (s: string) => {
    const t = s.replace(/\s+/g, '').trim();
    if (Array.from(t).length < 2 || Array.from(t).length > 10) return;
    if (/^(なし|無し|未定|特になし|オンライン.*|全国.*)$/.test(t)) return;
    if (/[0-9０-９]|徒歩|から|車で|より/.test(t)) return; // 「JR新倉敷駅から車で約7分」のような道案内は地名に入れない
    if (!out.includes(t)) out.push(t);
  };
  const a = String(area || '').replace(/\s+/g, '');
  const parts = a.split(/(?<=[都道府県市区町村郡])/).filter(Boolean);
  for (const p of parts) {
    if (/[都道府県]$/.test(p) && parts.length > 1) continue;
    const bare = p.replace(/[市区町村郡]$/, '');
    add(Array.from(bare).length >= 2 ? bare : p);
  }
  for (const t of String(localTerms || '').split(/[、,\/／\s　\n・]+/)) add(t.replace(/駅$/, ''));
  return out.slice(0, 6);
}

/**
 * 生成プロンプトの末尾に付ける「地元の会話の回」の決まり（長さ・絵文字・締めの共通指示より優先）。
 * places が空なら呼ばない（地域の無いお店では使わない）。
 */
export function localTalkNote(opts: { places: readonly string[]; allowEmoji: boolean }): string {
  const places = opts.places.length ? opts.places.map((p) => `「${p}」`).join('') : '登録の地域';
  const emoji = opts.allowEmoji
    ? '絵文字は「ときどき」。入れない回のほうが多くてよい。入れるなら1〜2個まで（上の「絵文字を1〜3個、毎回」の指示よりこちらを優先）。'
    : '絵文字は使わない。';
  return `

【今回は「地元の会話」の回（ここまでの長さ・1行目・絵文字・締めの指示より優先・厳守）】
お店の宣伝ではなく、地元に住む人に話しかける、ふだんのつぶやきを1つだけ書く。店主が自分のスマホで、ふと打ったような文にする。
（実測：このアプリのお店で、店主が手で書いた「地元の人への小さな問いかけ」はAIの投稿より桁違いに見られ、返信も多く付いた。）
- 話題は次のどれか1つ：地元の食べ物・名物／地元の身近な場所や景色（川・海・駅・通り・公園など）／この季節の地元のこと／方言・言い方の違い／暮らしのあるある（家事・仕事・寝るとき・運転など、だれにでもあるちょっとした場面）。
- 地名（${places}のどれか）を1回だけ自然に入れる。1行目の頭でなくてよい。
- 最後は、地元の人が一言で答えられる具体的な小さな質問で終える（形の例：「〜派ですか？」「〜って言います？」「〜ですかね？」「〜教えてください」）。
- 長さは${LOCAL_TALK.targetMin}〜${LOCAL_TALK.targetMax}字（長くても80字）。1〜3行。説明・理由・オチ・締めの挨拶は足さない。
- 話し言葉で、きれいに整えすぎない。「…」「笑」「ー！」のような、人が打つ崩しを1つ入れてよい。
- ${emoji}
- 書かないこと：お店の名前・メニュー・施術・予約・料金・営業時間・「〜な人へ」・「国家資格」・体が良くなる／効果の話・宣伝の言葉・URL・ハッシュタグ。
- 書かないこと：「今日は〇〇がある」「今日は雨」のような、その日の出来事・イベント・天気の言い切り（確かめられないため）。日付が変わっても通じる話題にする。
- 地元の名物・場所・方言は、広く知られていて確かなものだけ。自信がなければ「〜の名物といえば何ですか？」のように相手に聞く形にして、自分では言い切らない。登録に無い地元のお店の名前・人の名前・数字は書かない。
- 書き手自身や家族の体験・過去は作らない（「うちの子が」「昔の私は」「私だけ？」など）。
- 「〜いませんか？」「〜と思いませんか？」「〜ですよね？」の形は使わない。「〜とは？」「何でしょう？」のように答えを伏せて終えない。
- 形の参考（言い回し・話題はそのまま使わない。この地域の話に置きかえる）：「（地名）の（食べ物）、（季節）でも食べる派ですか？笑」／「（地名）の人に聞きたいんですけど、（方言の言い方）って言います？」／「（だれにでもある場面）の人ー！ （ちょっとした体のこと）になってません？」`;
}

/** 本文の字数（空白を除く） */
export function localTalkLength(text: string): number {
  return Array.from(String(text ?? '').replace(/\s+/g, '')).length;
}

/** このお客様は地元の会話を作らない方か */
export function localTalkOptedOut(userId: number | null | undefined): boolean {
  return userId != null && LOCAL_TALK.optOutUserIds.includes(Number(userId));
}

/**
 * お客様が書き方の決まりで「地元の投稿はいらない」と決めているか（2026-10-21 お知らせ：
 * 「止めたいときは『決まり：地元の投稿はいらない』と送ってください」）。アカウントごと・コードの書き換えなしで止まる。
 */
export function localTalkOptedOutByRules(rules: readonly string[] | null | undefined): boolean {
  return (rules ?? []).some((r) => /(地元|地域)/.test(r) && /(いらない|要らない|不要|作らない|つくらない|止め|やめ|出さない|書かない|なし|無し)/.test(r));
}
